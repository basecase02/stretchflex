// Writes infra/template.yaml from template.src.yaml, with the CloudFront
// function (edge.template.js + the redirects in redirects.mjs) inlined.
// usage: node infra/build.mjs [host]   (host: the main address, e.g. stretchflex.au)
import { readFile, writeFile } from "node:fs/promises";
import { MOVED, ARCHIVES, ARCHIVE_TARGET } from "../redirects.mjs";

const dir = new URL(".", import.meta.url);
const host = process.argv[2] ?? "";
const code = (await readFile(new URL("edge.template.js", dir), "utf8"))
  .replace("__HOST__", host)
  .replace("__MOVED__", JSON.stringify(MOVED))
  .replace("__ARCHIVES__", JSON.stringify(ARCHIVES))
  .replace("__ARCHIVE_TARGET__", ARCHIVE_TARGET);
const indented = code.trimEnd().split("\n").map((l) => (l ? "        " + l : "")).join("\n");
const src = await readFile(new URL("template.src.yaml", dir), "utf8");
await writeFile(new URL("template.yaml", dir), "# Generated by infra/build.mjs from template.src.yaml. Do not edit.\n" + src.replace("__EDGE_CODE__", indented));
console.log(`template.yaml written (host: ${host || "none"})`);
